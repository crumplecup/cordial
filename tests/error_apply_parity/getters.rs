//! Complete getter storage contracts agree across loader frontends.
use super::projection;
use cordial::{CrateTarget, IrView, SourceDatabase};
use miette::{IntoDiagnostic, Result};
use std::path::Path;

pub const PACKAGE: &str = "apply_getters";

#[tracing::instrument(level = "debug", err(level = "warn"))]
pub fn write(root: &Path) -> Result<()> {
    let owned = "use derive_getters::Getters; use derive_more::{Display, Error};\n/// Located failure.\n#[derive(Debug, Display, Error, Getters)]\n#[display(\"{file}:{line}\")]\npub struct Failure {\n/// Source file.\nfile: String, line: u32 }\n";
    let borrowed = "use derive_getters::Getters;\n\n/// Generated by Cordial: error-field-storage v1; owner=Failure.file; getter-copy=inserted\ntype CordialFailureFileStorage = &'static str;\n#[derive(Getters)]\npub struct Failure { #[getter(copy)] file: CordialFailureFileStorage, line: u32 }\n";
    let mut cases = vec![owned.to_string(), borrowed.to_string()];
    for changed in [
        "#[getter(skip)] file: String",
        "#[getter(rename = \"location\")] file: String",
        "#[error(ignore)] file: String",
        "#[error(source)] file: String",
        "#[cfg(not(kani))] file: String",
        "file: &'static str",
        "#[getter(copy)] file: &'static str",
        "file: std::string::String",
        "file: &str",
        "file: ::String",
    ] {
        cases.push(owned.replace("file: String", changed));
    }
    for changed in [
        "#[cfg_attr(unix, display(\"{file}:{line}\"))]",
        "#[cfg_attr(unix, cfg_attr(all(), display(\"{}:{}\", file, line)))]",
        "#[cfg_attr(unix, display(\"{}\", file.capacity()))]",
        "#[cfg_attr(unix, display(\"{}\", opaque!()))]",
        "#[cfg_attr(unix, unknown)]",
        "#[cfg_attr(unix, cfg(not(kani)))]",
        "#[cfg_attr(unix, derive(Getters))]",
        "#[cfg(unix)]",
        "#[cfg_attr(unix, display(\"{}\", String::new()))]",
        "#[cfg_attr(unix, display(\"{}\", |left, right| left + right))]",
    ] {
        cases.push(owned.replace("#[display(\"{file}:{line}\")]", changed));
    }
    for changed in [
        "use unknown::Getters;",
        "use derive_getters::Getters; use other::Getters;",
        "#[cfg(unix)] use derive_getters::Getters;",
        "/// Import\nuse derive_getters::Getters;",
        "use derive_getters::Getters; use other::*;",
        "use derive_getters::Getters; mod derive_getters {}",
        "use derive_getters::Getters; extern crate other as derive_getters;",
        "use derive_getters::Getters; macro_rules! Getters { () => {} }",
        "use derive_getters::Getters; use other as derive_getters;",
    ] {
        cases.push(owned.replace("use derive_getters::Getters;", changed));
    }
    for changed in [
        "pub type CordialFailureFileStorage",
        "type CordialFailureFileStorage<'a>",
        "type CordialFailureFileStorage = String",
        "/// Extra documentation.\ntype CordialFailureFileStorage",
        "#[cfg(unix)] type CordialFailureFileStorage",
    ] {
        if changed.contains("= String") {
            cases.push(borrowed.replace("type CordialFailureFileStorage = &'static str", changed));
        } else {
            cases.push(borrowed.replace("type CordialFailureFileStorage", changed));
        }
    }
    cases.push(borrowed.replace("#[getter(copy)]", "#[getter(skip)]"));
    cases.push(borrowed.replace("#[getter(copy)]", "#[getter(copy)] #[getter(copy)]"));
    cases.push(borrowed.replace("owner=Failure.file", "owner=Other.file"));
    cases.push(
        borrowed
            .replace(
                "type CordialFailureFileStorage",
                "#[cfg(unix)] type CordialFailureFileStorage",
            )
            .replace("#[getter(copy)]", "#[cfg(unix)] #[getter(copy)]"),
    );
    cases.push(owned.replace("Failure", "Café"));
    cases.push(owned.replace("Getters", "ReadFields").replace(
        "use derive_getters::ReadFields",
        "use derive_getters::Getters as ReadFields",
    ));
    cases.push(
        owned
            .replace("Getters", "derive_getters::Getters")
            .replace("use derive_getters::derive_getters::Getters;", ""),
    );
    cases.push("fn names<'a>(value: &'a str) { opaque!('a, CordialFailureFileStorage, fn, self, r#type); let _ = value; }".to_string());
    let mut library = String::new();
    for (index, source) in cases.iter().enumerate() {
        library.push_str(&format!("mod case_{index};\n"));
        std::fs::write(root.join(format!("src/case_{index}.rs")), source).into_diagnostic()?;
    }
    std::fs::write(root.join("src/lib.rs"), library).into_diagnostic()
}

#[tracing::instrument(level = "debug", skip(database), err(level = "warn"))]
pub fn check(root: &Path, database: &mut SourceDatabase) -> Result<()> {
    let target = CrateTarget::new(PACKAGE, root);
    let baseline = projection::baseline(root, &target)?;
    let expected =
        serde_json::to_value(baseline.source_error_apply().into_diagnostic()?).into_diagnostic()?;
    let native = database.project(&target, &[]).into_diagnostic()?;
    let actual =
        serde_json::to_value(native.source_error_apply().into_diagnostic()?).into_diagnostic()?;
    let actual_files = actual["files"]
        .as_array()
        .ok_or_else(|| miette::miette!("files"))?;
    let expected_files = expected["files"]
        .as_array()
        .ok_or_else(|| miette::miette!("files"))?;
    assert_eq!(actual_files.len(), expected_files.len());
    let mut differences = Vec::new();
    for (actual, expected) in actual_files.iter().zip(expected_files) {
        assert_eq!(actual["snapshot"], expected["snapshot"]);
        if actual["getters"] != expected["getters"] {
            differences.push(format!(
                "{}: native={} compatibility={}",
                actual["snapshot"]["path"], actual["getters"], expected["getters"]
            ));
        }
    }
    assert!(differences.is_empty(), "{}", differences.join("\n"));
    let first = actual_files
        .iter()
        .find(|file| {
            file["snapshot"]["path"] == root.join("src/case_0.rs").to_string_lossy().as_ref()
        })
        .ok_or_else(|| miette::miette!("owned"))?;
    assert!(first["getters"]["fields"][0]["storage"]["Owned"]["insertion"].is_object());
    let reverse = actual_files
        .iter()
        .find(|file| {
            file["snapshot"]["path"] == root.join("src/case_1.rs").to_string_lossy().as_ref()
        })
        .ok_or_else(|| miette::miette!("borrowed"))?;
    assert!(reverse["getters"]["fields"][0]["storage"]["Generated"]["edits"].is_array());
    Ok(())
}
