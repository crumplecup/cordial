/// The key `id` is the number of.
#[instrument(level = "trace", skip(id))]
pub(super) fn key_for<'db>(id: SemanticItemId) -> ItemKey<'db> {
    ItemKey::from_id(salsa::Id::from_bits(id.bits()))
}

/// What `id` describes, as text.
#[instrument(level = "trace", skip(db, id))]
pub(super) fn description(db: &RootDatabase, id: SemanticItemId) -> String {
    ItemKey::from_id(salsa::Id::from_bits(id.bits()))
        .descriptor(db)
        .clone()
}

/// The definition `id` names, found again from its description, or `None` when
/// it was described without a site (or its file is no longer here).
#[instrument(level = "trace", skip(db, id))]
pub(super) fn definition(db: &RootDatabase, id: SemanticItemId) -> Option<ModuleDef> {
    let key = ItemKey::from_id(salsa::Id::from_bits(id.bits()));
    let found = resolve(db, key);
    if found.is_none() {
        tracing::debug!(
            target: "cordial::semantic::identity",
            description = %key.descriptor(db),
            "no definition found again from its description"
        );
    }
    found
}

#[salsa::tracked(returns(copy))]
#[instrument(level = "debug", skip(db, key))]
#[hotpath::measure]
fn resolve<'db>(db: &'db dyn SemanticDatabase, key: ItemKey<'db>) -> Option<ModuleDef> {
    let root = db.root_database();
    let descriptor = key.descriptor(db);
    let site = Site::parse(descriptor)?;
    let file = file_at(root, &site.path)?;
    let direct = attach_db(root, || {
        let sema = Semantics::new(root);
        let tree = sema.parse(sema.attach_first_edition_opt(file)?);
        let candidates: Vec<ModuleDef> = match site.chain.len() {
            // A function synthesized for a derive is written nowhere: only the index has it.
            _ if site.member.is_some() => Vec::new(),
            // A file in several crates holds one definition for each: the candidates are the
            // first crate's, and only the description (which names the crate) says whether this
            // is that one; the other crates' definitions are in their crates' indexes.
            0 => node_at(root, file, &tree, &site.place)
                .and_then(|owner| written_in_file(&sema, owner, site.kind))
                .into_iter()
                .collect(),
            // A function an attribute macro generated: the annotated function is
            // where the call is.
            1 if site.kind == KIND_FUNCTION => annotated_function(root, file, &sema, &tree, &site),
            _ => Vec::new(),
        };
        // Whatever was found must say it is this definition.
        candidates
            .into_iter()
            .find(|candidate| describe(root, *candidate) == *descriptor)
    });
    // Anything else a macro generated (a derive's methods, what two attribute macros wrapped,
    // what a `macro_rules!` call defined) has no text to read the definition from: it is in
    // the crate's index of what was generated.
    direct.or_else(|| {
        if site.chain.is_empty() && site.member.is_none() && site.krate.is_empty() {
            return None;
        }
        ra_ap_ide_db::base_db::relevant_crates(root, file)
            .iter()
            .find_map(|krate| generated_in(db, *krate).get(descriptor.as_str()).copied())
    })
}

/// Every definition of `krate` that a macro generated, by description: the way back from a
/// description to a definition with no text of its own to read it from. Built once for the
/// crate, and out of date when anything the crate's definitions depend on has changed.
#[salsa::tracked(returns(ref))]
#[instrument(level = "debug", skip(db))]
#[hotpath::measure]
fn generated_in(
    db: &dyn SemanticDatabase,
    krate: ra_ap_ide_db::base_db::Crate,
) -> std::collections::HashMap<String, ModuleDef> {
    let root = db.root_database();
    attach_db(root, || {
        super::context_crates::declared_in(root, ra_ap_hir::Crate::from(krate))
            .into_iter()
            .filter(|definition| {
                site_of(root, *definition).is_some_and(|site| {
                    !site.chain.is_empty() || site.member.is_some() || !site.krate.is_empty()
                })
            })
            .map(|definition| (describe(root, definition), definition))
            .collect()
    })
}

/// The definition `owner`, an item written in the file, declares.
#[instrument(level = "trace", skip(sema, owner))]
fn written_in_file(
    sema: &Semantics<'_, RootDatabase>,
    owner: SyntaxNode,
    kind: u8,
) -> Option<ModuleDef> {
    match kind {
        KIND_FUNCTION => {
            let function = ast::Fn::cast(owner)?;
            sema.to_def(&function)
                .or_else(|| expanded_definition(sema, &function))
                .map(ModuleDef::Function)
        }
        KIND_STRUCT => sema
            .to_def(&ast::Struct::cast(owner)?)
            .map(|it| Adt::from(it).into()),
        KIND_ENUM => sema
            .to_def(&ast::Enum::cast(owner)?)
            .map(|it| Adt::from(it).into()),
        KIND_UNION => sema
            .to_def(&ast::Union::cast(owner)?)
            .map(|it| Adt::from(it).into()),
        KIND_TRAIT => sema.to_def(&ast::Trait::cast(owner)?).map(ModuleDef::Trait),
        KIND_ALIAS => sema
            .to_def(&ast::TypeAlias::cast(owner)?)
            .map(ModuleDef::TypeAlias),
        KIND_CONST => sema.to_def(&ast::Const::cast(owner)?).map(ModuleDef::Const),
        KIND_STATIC => sema
            .to_def(&ast::Static::cast(owner)?)
            .map(ModuleDef::Static),
        _ => None,
    }
}

/// What the function written at the site's place could be: the definition its attribute
/// macros expand to, or the function itself.
#[instrument(level = "trace", skip(db, sema, tree, site))]
fn annotated_function(
    db: &RootDatabase,
    file: FileId,
    sema: &Semantics<'_, RootDatabase>,
    tree: &ast::SourceFile,
    site: &Site,
) -> Vec<ModuleDef> {
    let Some(function) = node_at(db, file, tree, &site.place).and_then(ast::Fn::cast) else {
        return Vec::new();
    };
    expanded_definition(sema, &function)
        .into_iter()
        .chain(sema.to_def(&function))
        .map(ModuleDef::Function)
        .collect()
}

const KIND_FUNCTION: u8 = 1;
const KIND_STRUCT: u8 = 2;
const KIND_ENUM: u8 = 3;
const KIND_UNION: u8 = 4;
const KIND_TRAIT: u8 = 5;
const KIND_ALIAS: u8 = 6;
const KIND_CONST: u8 = 7;
const KIND_STATIC: u8 = 8;

/// Where a definition is written, as the database sees it.
///
/// A definition written in a file has its `place` in that file (see [`place_in_file`]) and an
/// empty `chain`. One a macro generated has the place of the outermost call that produced it
/// in the real file, and the `chain` of offsets inside each expansion on the way there, so two
/// invocations of one macro are two sites.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub(super) struct DefSite {
    pub(super) kind: u8,
    pub(super) file: FileId,
    pub(super) place: String,
    pub(super) chain: Vec<u32>,
    /// For a function the compiler synthesizes for a derive: the trait and method, written
    /// beside the site of the type it is for.
    pub(super) member: Option<String>,
    /// The root file of the crate the definition is in, when its file is in more than one crate
    /// (a test support module each test binary includes): the file alone does not say which.
    pub(super) krate: String,
}

/// A [`DefSite`] with its file named by path, which means the same in every process.
#[derive(Debug, Clone, PartialEq, Eq)]
struct Site {
    kind: u8,
    path: PathText,
    place: String,
    chain: Vec<u32>,
    member: Option<String>,
    krate: String,
}

/// A file's path in the database, and whether the database holds it as a real
/// path or a virtual one.
#[derive(Debug, Clone, PartialEq, Eq)]
struct PathText {
    real: bool,
    text: String,
}

impl PathText {
    #[instrument(level = "trace", skip(path))]
    fn of(path: &VfsPath) -> Option<Self> {
        match path.as_path() {
            Some(real) => Some(Self {
                real: true,
                text: real.to_string(),
            }),
            None => Some(Self {
                real: false,
                text: path.to_string(),
            }),
        }
    }

    #[instrument(level = "trace", skip(self))]
    fn vfs(&self) -> VfsPath {
        if self.real {
            VfsPath::new_real_path(self.text.clone())
        } else {
            VfsPath::new_virtual_path(self.text.clone())
        }
    }
}

impl Site {
    #[instrument(level = "trace", skip(text))]
    fn parse(text: &str) -> Option<Self> {
        let mut parts = text.splitn(7, '|');
        let kind = parts.next()?.parse().ok()?;
        let real = match parts.next()? {
            "real" => true,
            "virtual" => false,
            _ => return None,
        };
        let place = parts.next()?.to_owned();
        let chain = parts.next()?;
        let chain = if chain.is_empty() {
            Vec::new()
        } else {
            chain
                .split(',')
                .map(|part| part.parse().ok())
                .collect::<Option<Vec<u32>>>()?
        };
        let member = match parts.next()? {
            "" => None,
            member => Some(member.to_owned()),
        };
        let krate = parts.next()?.to_owned();
        Some(Self {
            kind,
            path: PathText {
                real,
                text: parts.next()?.to_owned(),
            },
            place,
            chain,
            member,
            krate,
        })
    }

    #[instrument(level = "trace", skip(self))]
    fn text(&self) -> String {
        let route = if self.path.real { "real" } else { "virtual" };
        let chain = self
            .chain
            .iter()
            .map(u32::to_string)
            .collect::<Vec<_>>()
            .join(",");
        format!(
            "{}|{route}|{}|{chain}|{}|{}|{}",
            self.kind,
            self.place,
            self.member.as_deref().unwrap_or(""),
            self.krate,
            self.path.text
        )
    }
}

/// Where `definition` is written, when it has a site at all.
#[instrument(level = "trace", skip(db, definition))]
pub(super) fn site_of(db: &RootDatabase, definition: ModuleDef) -> Option<DefSite> {
    let mut site = site_written(db, definition)?;
    site.krate = shared_file_crate(db, definition, site.file).unwrap_or_default();
    Some(site)
}

/// The root file of the crate `definition` is in, when `file` is in several crates.
#[instrument(level = "trace", skip(db, definition))]
fn shared_file_crate(db: &RootDatabase, definition: ModuleDef, file: FileId) -> Option<String> {
    if ra_ap_ide_db::base_db::relevant_crates(db, file).len() < 2 {
        return None;
    }
    let krate = definition.module(db)?.krate(db);
    Some(path_of(db, krate.root_file(db))?.text)
}

#[instrument(level = "trace", skip(db, definition))]
fn site_written(db: &RootDatabase, definition: ModuleDef) -> Option<DefSite> {
    match definition {
        ModuleDef::Function(it) => {
            derived_site(db, it).or_else(|| site_in(db, KIND_FUNCTION, it.source(db)?))
        }
        ModuleDef::Adt(Adt::Struct(it)) => site_in(db, KIND_STRUCT, it.source(db)?),
        ModuleDef::Adt(Adt::Enum(it)) => site_in(db, KIND_ENUM, it.source(db)?),
        ModuleDef::Adt(Adt::Union(it)) => site_in(db, KIND_UNION, it.source(db)?),
        ModuleDef::Trait(it) => site_in(db, KIND_TRAIT, it.source(db)?),
        ModuleDef::TypeAlias(it) => site_in(db, KIND_ALIAS, it.source(db)?),
        ModuleDef::Const(it) => site_in(db, KIND_CONST, it.source(db)?),
        ModuleDef::Static(it) => site_in(db, KIND_STATIC, it.source(db)?),
        _ => None,
    }
}

/// The site of a function the compiler synthesizes for a built-in derive. Its source is the
/// trait's own method (`Clone::clone` in `core`), the same for every type that derives the
/// trait, so it is described by the type the impl is for, the trait and the method.
#[instrument(level = "trace", skip(db, function))]
fn derived_site(db: &RootDatabase, function: ra_ap_hir::Function) -> Option<DefSite> {
    let source = function.source(db)?;
    let own = function.module(db).krate(db).base();
    let file = source
        .file_id
        .original_file_respecting_includes(db)
        .file_id(db);
    if ra_ap_ide_db::base_db::relevant_crates(db, file).contains(&own) {
        return None;
    }
    let ra_ap_hir::AssocItemContainer::Impl(implementation) =
        ra_ap_hir::AsAssocItem::as_assoc_item(function, db)?.container(db)
    else {
        return None;
    };
    let adt = implementation.self_ty(db).as_adt()?;
    let derived = implementation.trait_(db)?;
    let mut site = site_of(db, ModuleDef::Adt(adt))?;
    site.kind = KIND_FUNCTION;
    site.member = Some(format!(
        "{}::{}",
        derived.name(db).as_str(),
        function.name(db).as_str()
    ));
    Some(site)
}

/// The site of an item's name, following each macro expansion out to the call that
/// produced it.
#[instrument(level = "trace", skip(db, source))]
fn site_in<N: AstNode + HasName>(
    db: &RootDatabase,
    kind: u8,
    source: InFile<N>,
) -> Option<DefSite> {
    let name = source.value.name()?;
    let mut file_id = source.file_id;
    let mut node = name.syntax().parent()?;
    let mut offset = u32::from(name.syntax().text_range().start());
    let mut chain = Vec::new();
    while file_id.is_macro() {
        chain.push(offset);
        let call = file_id.call_node(db)?;
        offset = u32::from(call.value.text_range().start());
        node = call.value;
        file_id = call.file_id;
    }
    let file = file_id.original_file_respecting_includes(db).file_id(db);
    Some(DefSite {
        kind,
        file,
        place: place_in_file(db, file, &node),
        chain,
        member: None,
        krate: String::new(),
    })
}

/// What names `node` among the items of its file, if it is one that can be named: the kind of
/// item and its name, an impl's trait and type, a macro call's or an attribute's path.
#[instrument(level = "trace", skip(node))]
fn label(node: &SyntaxNode) -> Option<String> {
    fn named<N: AstNode + HasName>(tag: &str, node: &SyntaxNode) -> Option<String> {
        Some(format!("{tag} {}", N::cast(node.clone())?.name()?.text()))
    }
    fn squeezed(node: Option<impl AstNode>) -> String {
        node.map(|node| {
            node.syntax()
                .text()
                .to_string()
                .split_whitespace()
                .collect()
        })
        .unwrap_or_default()
    }
    let text = match node.kind() {
        SyntaxKind::FN => named::<ast::Fn>("fn", node)?,
        SyntaxKind::STRUCT => named::<ast::Struct>("struct", node)?,
        SyntaxKind::ENUM => named::<ast::Enum>("enum", node)?,
        SyntaxKind::UNION => named::<ast::Union>("union", node)?,
        SyntaxKind::TRAIT => named::<ast::Trait>("trait", node)?,
        SyntaxKind::TYPE_ALIAS => named::<ast::TypeAlias>("type", node)?,
        SyntaxKind::CONST => named::<ast::Const>("const", node)?,
        SyntaxKind::STATIC => named::<ast::Static>("static", node)?,
        SyntaxKind::MODULE => named::<ast::Module>("mod", node)?,
        SyntaxKind::MACRO_RULES => named::<ast::MacroRules>("macro_rules", node)?,
        SyntaxKind::IMPL => {
            let implementation = ast::Impl::cast(node.clone())?;
            format!(
                "impl {} for {}",
                squeezed(implementation.trait_()),
                squeezed(implementation.self_ty())
            )
        }
        SyntaxKind::MACRO_CALL => {
            format!(
                "call {}",
                squeezed(ast::MacroCall::cast(node.clone())?.path())
            )
        }
        // The call a derive macro is expanded from is the attribute, not the type. No other
        // attribute is a call (an attribute macro's is the item it is on), and a file has far
        // more of them than items, so only `derive` is given a place.
        SyntaxKind::ATTR => {
            let path = squeezed(ast::Attr::cast(node.clone())?.path());
            if path != "derive" {
                return None;
            }
            format!("attr {path}")
        }
        // What a derive is expanded from, in the newer syntax trees: the `derive(...)` inside the
        // attribute. Its path, not the list of derives, names it.
        SyntaxKind::TOKEN_TREE_META => {
            let text = node.text().to_string();
            let path: String = text
                .split('(')
                .next()
                .unwrap_or_default()
                .split_whitespace()
                .collect();
            if path != "derive" {
                return None;
            }
            format!("meta {path}")
        }
        _ => return None,
    };
    // `|` separates a description's fields and `/` a place's segments.
    Some(
        text.replace('%', "%25")
            .replace('|', "%7C")
            .replace('/', "%2F"),
    )
}

/// Every item of one file that has a place, by node and by place, built in one pass.
///
/// The place of an item is the labels of the modules, impls, traits and functions around it and of
/// the item itself, outermost first, each followed by `#n` when `n` earlier siblings have the same
/// label (two functions of one name under different `cfg`s). Adding text above or between items
/// changes nothing about it. Counting the earlier siblings of each item one by one, as a place is
/// worded, takes time in proportion to the square of the items a file has (thousands of impls
/// with one label), so the file is walked once and each parent keeps its own counts.
#[derive(Debug, Default, Clone, PartialEq, Eq)]
pub(super) struct PlaceIndex {
    by_node: std::collections::HashMap<(SyntaxKind, u32), String>,
    by_place: std::collections::HashMap<String, (SyntaxKind, u32)>,
}

/// What is known of the items counted under one node while walking a file.
struct Parent {
    /// The place of the nearest item at or above the node.
    place: std::rc::Rc<str>,
    /// How many items with each label were seen directly under the node so far.
    seen: std::collections::HashMap<(SyntaxKind, String), usize>,
}

impl PlaceIndex {
    #[instrument(name = "place_index", level = "debug", skip(root))]
    #[hotpath::measure(impl_type = "PlaceIndex")]
    fn of(root: &SyntaxNode) -> Self {
        use ra_ap_syntax::WalkEvent;
        let mut index = Self::default();
        let mut parents = vec![Parent {
            place: std::rc::Rc::from(""),
            seen: std::collections::HashMap::new(),
        }];
        for event in root.preorder() {
            match event {
                WalkEvent::Enter(node) => {
                    let place = match (label(&node), parents.last_mut()) {
                        (Some(label), Some(parent)) => {
                            let earlier =
                                parent.seen.entry((node.kind(), label.clone())).or_default();
                            let segment = match *earlier {
                                0 => label,
                                n => format!("{label}#{n}"),
                            };
                            *earlier += 1;
                            let place = match parent.place.is_empty() {
                                true => segment,
                                false => format!("{}/{segment}", parent.place),
                            };
                            let at = (node.kind(), u32::from(node.text_range().start()));
                            index.by_node.insert(at, place.clone());
                            index.by_place.insert(place.clone(), at);
                            std::rc::Rc::from(place)
                        }
                        (_, parent) => {
                            parent.map_or_else(|| std::rc::Rc::from(""), |p| p.place.clone())
                        }
                    };
                    parents.push(Parent {
                        place,
                        seen: std::collections::HashMap::new(),
                    });
                }
                WalkEvent::Leave(_) => {
                    parents.pop();
                }
            }
        }
        index
    }
}

/// A file, as the argument of the query that indexes its places.
#[salsa::interned(debug)]
struct PlacedFile<'db> {
    index: u32,
}

/// The places of `file`'s items, kept until the file's text changes.
#[salsa::tracked(returns(ref))]
#[instrument(level = "debug", skip(db), fields(file = *file.index(db)))]
#[hotpath::measure]
fn places_in<'db>(db: &'db dyn SemanticDatabase, file: PlacedFile<'db>) -> PlaceIndex {
    let root = db.root_database();
    let file_id = FileId::from_raw(*file.index(db));
    // A context's copy of a file has the text of its original, so it has its places: the index is
    // the original's, and the copy is not parsed and walked again for each context.
    if let Some(original) = original_of_copy(root, file_id) {
        tracing::debug!(target: "cordial::semantic::identity", file = file_id.index(), original = original.index(), "a copy takes its original's places");
        return index_of(root, original).clone();
    }
    tracing::debug!(target: "cordial::semantic::identity", file = file_id.index(), "indexing the places of a file");
    attach_db(root, || {
        let sema = Semantics::new(root);
        sema.attach_first_edition_opt(file_id)
            .map(|editioned| PlaceIndex::of(sema.parse(editioned).syntax()))
            .unwrap_or_default()
    })
}

/// The file `file` is a context's copy of, or `None` when it is not a copy.
#[instrument(level = "trace", skip(db))]
#[hotpath::measure]
fn original_of_copy(db: &RootDatabase, file: FileId) -> Option<FileId> {
    let path = path_of(db, file)?;
    let real = super::context_crates::original_path(&path.vfs())?;
    file_at(
        db,
        &PathText {
            real: true,
            text: real.to_string_lossy().into_owned(),
        },
    )
}

/// The index of `file`'s places.
#[instrument(level = "trace", skip(db))]
fn index_of(db: &RootDatabase, file: FileId) -> &PlaceIndex {
    let semantic: &dyn SemanticDatabase = db;
    places_in(semantic, PlacedFile::new(semantic, file.index()))
}

/// Where `node`, an item of `file`, is: see [`PlaceIndex`].
#[instrument(level = "trace", skip(db, node))]
pub(super) fn place_in_file(db: &RootDatabase, file: FileId, node: &SyntaxNode) -> String {
    let at = (node.kind(), u32::from(node.text_range().start()));
    let place = index_of(db, file).by_node.get(&at).cloned();
    if place.is_none() {
        tracing::debug!(
            target: "cordial::semantic::identity",
            kind = ?node.kind(),
            start = at.1,
            text = %node.text().to_string().chars().take(60).collect::<String>(),
            "a node with no place in its file"
        );
    }
    place.unwrap_or_default()
}

/// The item of `tree`, the parse of `file`, at `place`.
#[instrument(level = "trace", skip(db, tree))]
fn node_at(
    db: &RootDatabase,
    file: FileId,
    tree: &ast::SourceFile,
    place: &str,
) -> Option<SyntaxNode> {
    let (kind, start) = *index_of(db, file).by_place.get(place)?;
    tree.syntax()
        .token_at_offset(TextSize::from(start))
        .right_biased()?
        .parent_ancestors()
        .find(|node| node.kind() == kind && u32::from(node.text_range().start()) == start)
}

/// The path the database holds `file` at.
#[instrument(level = "trace", skip(db))]
fn path_of(db: &RootDatabase, file: FileId) -> Option<PathText> {
    let root: SourceRootId = db.file_source_root(file).source_root_id(db);
    let source_root = db.source_root(root).source_root(db);
    PathText::of(source_root.path_for_file(&file)?)
}

/// The path the database holds `file` at, as the virtual file system names it.
#[instrument(level = "trace", skip(db))]
pub(super) fn vfs_path_of(db: &RootDatabase, file: FileId) -> Option<VfsPath> {
    path_of(db, file).map(|path| path.vfs())
}

/// The file the database holds at `path`.
#[instrument(level = "trace", skip(db))]
#[hotpath::measure]
fn file_at(db: &RootDatabase, path: &PathText) -> Option<FileId> {
    let wanted = path.vfs();
    // A context's copy is in that context's source root and nowhere else, and any other file
    // is in none of them: looking where the file cannot be would make what is found depend on
    // roots that have nothing to do with it (every context's copies, for an ordinary file).
    let copy_root = super::context_crates::copy_root_of(&wanted);
    db.files()
        .source_root_inputs()
        .into_iter()
        .filter(|(id, _)| match copy_root {
            Some(root) => *id == root,
            None => id.0 < ra_ap_ide_db::base_db::TOOL_SOURCE_ROOTS,
        })
        .find_map(|(_, root)| root.source_root(db).file_for_path(&wanted).copied())
}

/// The description of `definition`: its site, or a nonce of this process.
#[instrument(level = "trace", skip(db, definition))]
fn describe(db: &RootDatabase, definition: ModuleDef) -> String {
    let text = site_of(db, definition)
        .and_then(|site| {
            Some(
                Site {
                    kind: site.kind,
                    path: path_of(db, site.file)?,
                    place: site.place,
                    chain: site.chain,
                    member: site.member,
                    krate: site.krate,
                }
                .text(),
            )
        })
        .unwrap_or_else(|| format!("volatile|{}|{definition:?}", process_nonce()));
    // The spans this runs under say who asked: in a restored run nothing should need to.
    tracing::debug!(
        target: "cordial::semantic::identity",
        description = %text,
        "described a definition"
    );
    text
}

/// Text that is different in every process.
#[instrument(level = "trace")]
fn process_nonce() -> &'static str {
    static NONCE: OnceLock<String> = OnceLock::new();
    NONCE.get_or_init(|| {
        let nanos = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map_or(0, |elapsed| elapsed.as_nanos());
        format!("{}-{nanos}", std::process::id())
    })
}
