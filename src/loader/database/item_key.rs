//! Item identity that survives a process.
//!
//! A [`SemanticItemId`] used to be an index into a table the session interned
//! definitions in, so it meant something only until the process ended. It is now the
//! id of an interned *description* of the definition: where its name is written
//! (the file's path, the place in it, the kind). The same definition has the same
//! description in every process, so a database saved by one and restored by the next
//! gives it the same id, and a fact saved with ids can be read back.
//!
//! The table is immortal (`revisions = usize::MAX`): an id is never reused for
//! another definition. A definition with no source site of its own (generated by a
//! macro, say) is described with a nonce of this process, so it matches nothing in
//! another process: a saved fact about it reads back as an unknown definition, never
//! as a wrong one.

use std::sync::OnceLock;

use ra_ap_hir::{Adt, HasSource, InFile, ModuleDef, Semantics, attach_db};
use ra_ap_ide_db::RootDatabase;
use ra_ap_ide_db::base_db::{SourceDatabase as RaSourceDatabase, SourceRootId};
use ra_ap_syntax::{AstNode, SyntaxKind, SyntaxNode, TextSize, ast, ast::HasName};
use ra_ap_vfs::{FileId, VfsPath};
use salsa::plumbing::{AsId, FromId};
use tracing::instrument;

use super::populate::expanded_definition;
use super::queries::SemanticDatabase;
use crate::SemanticItemId;

/// The description of one definition.
#[salsa::interned(persist, revisions = usize::MAX)]
pub(super) struct ItemKey<'db> {
    #[returns(ref)]
    descriptor: String,
}

/// The identity of `definition` in this database.
#[instrument(level = "trace", skip(db, definition))]
#[hotpath::measure]
pub(super) fn identity(db: &RootDatabase, definition: ModuleDef) -> SemanticItemId {
    SemanticItemId::new(ItemKey::new(db, describe(db, definition)).as_id().as_bits())
}

/// The description of the scope "all the functions of this crate": the crate's root file, which is
/// where the same crate is found again in another process. `None` for a crate whose root file has no
/// path of its own.
#[instrument(level = "trace", skip(db))]
#[hotpath::measure]
pub(super) fn crate_scope(db: &RootDatabase, krate: ra_ap_hir::Crate) -> Option<ItemKey<'_>> {
    let path = path_of(db, krate.root_file(db))?;
    Some(ItemKey::new(db, format!("crate|{}", path.text)))
}

/// The files of the crate `scope` describes, as the paths the database holds them at: those of its
/// modules, each once, and those `include!` brings in. `None` for a scope that is not a crate of
/// this database.
///
/// Saved with the database: asking the crate for its modules builds its definition map and those
/// of everything it depends on, which are not saved, and the answer changes only with the sources.
#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub(super) struct CrateFiles {
    modules: Vec<(bool, String)>,
    included: Vec<(bool, String)>,
}

#[salsa::tracked(persist, returns(ref))]
#[instrument(level = "debug", skip(db, scope))]
#[hotpath::measure]
fn crate_files<'db>(db: &'db dyn SemanticDatabase, scope: ItemKey<'db>) -> Option<CrateFiles> {
    let root = db.root_database();
    attach_db(root, || {
        let krate = crate_of(root, scope.descriptor(root))?;
        let named = |files: std::collections::BTreeSet<FileId>| -> Vec<(bool, String)> {
            files
                .into_iter()
                .filter_map(|file| path_of(root, file))
                .map(|path| (path.real, path.text))
                .collect()
        };
        let modules: std::collections::BTreeSet<FileId> = krate
            .modules(root)
            .into_iter()
            .map(|module| {
                module
                    .definition_source_file_id(root)
                    .original_file_respecting_includes(root)
                    .file_id(root)
            })
            .collect();
        let included: std::collections::BTreeSet<FileId> =
            ra_ap_hir_def::include_macro_invoc(root, krate.base())
                .iter()
                .map(|(_, file)| file.file_id(root))
                .collect();
        Some(CrateFiles {
            modules: named(modules),
            included: named(included),
        })
    })
}

/// The files of `krate`'s modules, found again from the saved list without building definition
/// maps when nothing changed.
#[instrument(level = "trace", skip(db))]
#[hotpath::measure]
pub(super) fn files_of(db: &RootDatabase, krate: ra_ap_hir::Crate) -> Option<Vec<FileId>> {
    Some(files_in(db, &saved_files(db, krate)?.modules))
}

/// The files `include!` brings into `krate`, from the same saved list.
#[instrument(level = "trace", skip(db))]
#[hotpath::measure]
pub(super) fn included_files_of(db: &RootDatabase, krate: ra_ap_hir::Crate) -> Option<Vec<FileId>> {
    Some(files_in(db, &saved_files(db, krate)?.included))
}

#[instrument(level = "trace", skip(db))]
fn saved_files(db: &RootDatabase, krate: ra_ap_hir::Crate) -> Option<&CrateFiles> {
    let scope = crate_scope(db, krate)?;
    let semantic: &dyn SemanticDatabase = db;
    crate_files(semantic, scope).as_ref()
}

#[instrument(level = "trace", skip(db, listed))]
#[hotpath::measure]
fn files_in(db: &RootDatabase, listed: &[(bool, String)]) -> Vec<FileId> {
    listed
        .iter()
        .filter_map(|(real, text)| {
            file_at(
                db,
                &PathText {
                    real: *real,
                    text: text.clone(),
                },
            )
        })
        .collect()
}

/// The description of the scope "this file": where the database holds it.
#[instrument(level = "trace", skip(db))]
#[hotpath::measure]
pub(super) fn file_scope(db: &RootDatabase, file: FileId) -> Option<ItemKey<'_>> {
    let path = path_of(db, file)?;
    let route = if path.real { "real" } else { "virtual" };
    Some(ItemKey::new(db, format!("file|{route}|{}", path.text)))
}

/// The file `scope` describes, found again by its path.
#[instrument(level = "trace", skip(db))]
#[hotpath::measure]
pub(super) fn file_of_scope(db: &RootDatabase, scope: &str) -> Option<FileId> {
    let rest = scope.strip_prefix("file|")?;
    let (route, text) = rest.split_once('|')?;
    file_at(
        db,
        &PathText {
            real: route == "real",
            text: text.to_owned(),
        },
    )
}

/// What a context's copy of a definition stands for in the ordinary build: the description of the
/// definition at the same place of the original file, when the ordinary build has one. `None` for
/// a description that is not a copy's, or whose original is not there.
///
/// A copy's description is the original's with the copy's file named for the original's, and the
/// crate named for the original's, so the original's is written down from the copy's alone. Saved
/// with the database, so a restored run does not ask rust-analyzer to match them.
#[salsa::tracked(persist, returns(ref))]
#[instrument(level = "debug", skip(db, key))]
#[hotpath::measure]
fn canonical_description<'db>(db: &'db dyn SemanticDatabase, key: ItemKey<'db>) -> Option<String> {
    let mut site = Site::parse(key.descriptor(db))?;
    let original = super::context_crates::original_path(&site.path.vfs())?;
    site.path = PathText {
        real: true,
        text: original.to_string_lossy().into_owned(),
    };
    if !site.krate.is_empty() {
        let root = VfsPath::new_virtual_path(site.krate.clone());
        site.krate = super::context_crates::original_path(&root)?
            .to_string_lossy()
            .into_owned();
    }
    let text = site.text();
    resolve(db, ItemKey::new(db, text.clone()))?;
    Some(text)
}

/// The identity facts about a context's copy of a definition are given, in place of its own: the
/// ordinary build's definition at the same place when there is one.
#[instrument(level = "trace", skip(db, id))]
#[hotpath::measure]
pub(super) fn canonical_id(db: &RootDatabase, id: SemanticItemId) -> SemanticItemId {
    let semantic: &dyn SemanticDatabase = db;
    match canonical_description(semantic, key_for(id)) {
        Some(text) => SemanticItemId::new(ItemKey::new(db, text.clone()).as_id().as_bits()),
        None => id,
    }
}

/// The crate `scope` describes, found again by its root file.
#[instrument(level = "trace", skip(db))]
#[hotpath::measure]
pub(super) fn crate_of(db: &RootDatabase, scope: &str) -> Option<ra_ap_hir::Crate> {
    let wanted = scope.strip_prefix("crate|")?;
    ra_ap_hir::Crate::all(db)
        .into_iter()
        .find(|krate| path_of(db, krate.root_file(db)).is_some_and(|path| path.text == wanted))
}

/// The interned description of `definition`.
#[instrument(level = "trace", skip(db, definition))]
pub(super) fn key_of(db: &RootDatabase, definition: ModuleDef) -> ItemKey<'_> {
    ItemKey::new(db, describe(db, definition))
}

/// Whether `key`'s description finds `definition` again: the test of whether a result
/// computed for the description may stand for this definition.
#[instrument(level = "trace", skip(db, key, definition))]
pub(super) fn finds(db: &dyn SemanticDatabase, key: ItemKey<'_>, definition: ModuleDef) -> bool {
    resolve(db, key) == Some(definition)
}

/// The function `key` describes, when it describes one that can be found again.
#[instrument(level = "trace", skip(db, key))]
pub(super) fn function_of(
    db: &dyn SemanticDatabase,
    key: ItemKey<'_>,
) -> Option<ra_ap_hir::Function> {
    match resolve(db, key)? {
        ModuleDef::Function(function) => Some(function),
        _ => None,
    }
}

/// The number of `key`, as it appears in events.
#[instrument(level = "trace", skip(key))]
pub(super) fn key_bits(key: ItemKey<'_>) -> u64 {
    key.as_id().as_bits()
}

